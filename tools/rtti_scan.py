"""List the C++ classes of a DMC3 ELF from Metrowerks RTTI.

An MW vtable is laid out as {RTTI *, this-adjust offset, slot0, slot1, ...},
and an RTTI record as {const char *name, base list *}. This scans the data for
vtables whose RTTI name is a C identifier and prints, for each one:
    <vtable addr> <class> <offset> <slot count> <slot0 ...>
Secondary vtables (multiple inheritance) have a negative offset. Then, one per
class, the RTTI base list (all ancestors with their subobject offsets):
    bases <class> <ancestor>@<hex offset> ...

usage: python -I tools/rtti_scan.py orig/SLUS_209.64/SLUS_209.64 [> config/SLUS_209.64/rtti.txt]
"""
import re
import struct
import sys

BASE, HDR = 0x100000, 0x80


def main(path, text_end=0x50FF08, data_start=0x510000, data_end=0x5BE080):
    d = open(path, "rb").read()
    word = lambda a: struct.unpack_from("<I", d, a - BASE + HDR)[0]

    def cstr(a):
        if not (data_start - 0x100000 <= a < data_end):
            return None
        o = a - BASE + HDR
        s = d[o:o + 64].split(b"\0")[0]
        return s.decode() if re.fullmatch(rb"[A-Za-z_][A-Za-z0-9_]{1,62}", s) else None

    is_text = lambda a: BASE <= a < text_end and a % 4 == 0
    rows = []
    a = data_start
    while a < data_end - 12:
        r, off, s0 = word(a), word(a + 4), word(a + 8)
        if data_start - 0x100000 <= r < data_end and r % 4 == 0 and is_text(s0) and \
                (off == 0 or off >= 0xFFFF0000):
            name = cstr(word(r))
            if name:
                slots = []
                b = a + 8
                while b < data_end and is_text(word(b)):
                    slots.append(word(b))
                    b += 4
                off_s = off - (1 << 32) if off & 0x80000000 else off
                rows.append((a, name, off_s, slots))
                a = b
                continue
        a += 4
    classes = sorted({r[1] for r in rows})
    print(f"# {len(rows)} vtables, {len(classes)} classes (from MW RTTI); generated by tools/rtti_scan.py")
    for a, name, off, slots in rows:
        print(f"{a:08X} {name} {off} {len(slots)} " + " ".join(f"{s:08X}" for s in slots))
    done = set()
    for a, name, off, slots in rows:
        if off or name in done:
            continue
        done.add(name)
        b, bases = word(word(a) + 4), []
        while b:
            r = word(b)
            if r == 0:
                break
            bases.append(f"{cstr(word(r))}@{word(b + 4):X}")
            b += 8
        print(f"bases {name} " + " ".join(bases))


if __name__ == "__main__":
    main(sys.argv[1])
