"""Generate flat constructors straight from the original asm, verified byte-for-byte.

Shape: `char *f(char *p) { BODY; return p; }` (or a void `f(p) { BODY }`) with the one-register frame
(`addiu sp,-0x20; sd ra,0x10(sp); sq s0,0(sp)`, `p` kept in s0, `daddu v0,s0` before the epilogue).
BODY is interpreted with the same symbolic translator as tools/gen_flat_dtors.py: base-constructor
calls, vtable stores, constant/zero member stores, member null checks and calls whose arguments are
`p + K`, constants, symbols or function addresses. Only byte-matching functions are kept.
Output: src/game/auto/flat_ctors.c

usage: python -I tools/gen_flat_ctors.py
"""
import re, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_flat_dtors as fd

ROOT = fd.ROOT
OUT = ROOT / "src/game/auto/flat_ctors.c"
PRO = ["addiu $sp, $sp, -0x20", "sd $ra, 0x10($sp)", "sq $s0, 0x0($sp)"]
EPI = ["ld $ra, 0x10($sp)", "lq $s0, 0x0($sp)", "jr $ra", "addiu $sp, $sp, 0x20"]


def gen(name, items):
    ins = [fd.norm(x) if k == "ins" else x for k, x in items]
    kinds = [k for k, _ in items]
    if ins[0] != PRO[0] or ins[-4:] != EPI or "label" in kinds[-4:]:
        raise fd.Fail("prologue")
    # the scheduler interleaves body instructions with the register saves
    body = list(zip(kinds[1:-4], ins[1:-4]))
    for x in PRO[1:]:
        if ("ins", x) not in body[:8] or any(k != "ins" for k, _ in body[:body.index(("ins", x))]):
            raise fd.Fail("prologue")
        body.remove(("ins", x))
    # without `daddu v0,s0` the function is void (a trailing call's result may pass through)
    ret = ("ins", "daddu $v0, $s0, $zero") in body
    # p must reach s0 before anything else uses s0, and nothing may jump to the epilogue
    first = [i for i, (_, x) in enumerate(body) if "$s0" in x]
    if not first or body[first[0]][1] != "daddu $s0, $a0, $zero":
        raise fd.Fail("p not in s0")
    if any(k == "ins" and x.split()[0] in ("jr", "jalr", "bnez", "beq", "bne", "b", "blez", "bgez",
                                             "bltz", "bgtz", "bc1t", "bc1f") for k, x in body):
        raise fd.Fail("control flow")
    lines, decls = fd.interp(body, "$s0", 1, live=("$a0",))
    # K&R definition: no prototype, so callers that pass extra (ignored) arguments still compile
    code = "%s %s(p) char *p; {\n" % ("char *" if ret else "void", name)
    code += "\n".join(lines) + ("\n" if lines else "")
    code += ("    return p;\n" if ret else "") + "}\n"
    return code, decls


def defined():
    out = set()
    for p in (ROOT / "src").rglob("*"):
        if p.suffix not in (".c", ".cpp") or p == OUT:
            continue
        for l in p.read_text(errors="replace").splitlines():
            m = re.match(r"^[^ #/].*?\b(func_[0-9A-F]{8})\(.*\{", l)
            if m:
                out.add(m.group(1))
    for p in (ROOT / "config/SLUS_209.64").glob("symbols*.txt"):
        for l in p.read_text(errors="replace").splitlines():
            m = re.match(r"\s*(\S+)\s*=\s*0x([0-9A-Fa-f]+)", l)
            if m and not m.group(1).startswith("func_"):
                out.add("func_%08X" % int(m.group(2), 16))
    return out


def write(ok, alld):
    names = {n for n, _ in ok}
    decls = sorted(d for d in alld if not any(n in d for n in names))
    with open(OUT, "w", newline="\n") as f:
        f.write("/* AUTO-GENERATED by tools/gen_flat_ctors.py: flat constructors translated from the\n"
                " * original asm and verified byte-for-byte (only matches are kept). */\n")
        f.write("".join("%s %s();\n" % ("char *" if c.startswith("char") else "void", n) for n, c in ok))
        f.write("\n".join(decls) + "\n\n")
        for _, code in ok:
            f.write(code + "\n")


def main():
    defd = defined()
    ok, alld, why = [], set(), {}
    for name, items in fd.funcs.items():
        a = int(name[5:], 16)
        if name in defd or a < 0x195400 or a >= 0x50F000:
            continue
        try:
            code, decls = gen(name, items)
        except fd.Fail as e:
            k = str(e).split()[0]
            why[k] = why.get(k, 0) + 1
            continue
        except Exception:
            continue
        ok.append((name, code))
        alld |= decls
    write(ok, alld)
    r = subprocess.run([sys.executable, "-I", str(ROOT / "tools/try.py"), str(OUT)] + [n for n, _ in ok],
                       capture_output=True, text=True, cwd=ROOT)
    good = set(re.findall(r"(func_[0-9A-F]{8}) @ 0x[0-9a-f]+: \d+/\d+ instructions match .*MATCH", r.stdout))
    kept = [(n, c) for n, c in ok if n in good]
    write(kept, alld)
    if "-v" in sys.argv:
        print(sorted(why.items(), key=lambda kv: -kv[1])[:12])
        print([n for n, _ in ok if n not in good][:30])
    print("%d generated, %d match" % (len(ok), len(kept)))


if __name__ == "__main__":
    main()
