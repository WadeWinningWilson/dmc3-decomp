"""Generate placeholder classes for MW empty-body deleting destructors (the
exact 17-instruction shape of 0x1AA7F0), verify each, and keep only matches.

Writes src/game/auto/dtors.cpp and config/SLUS_209.64/symbols.auto.txt (mangled
placeholder name -> address). Class names CUnk<addr> are placeholders.
usage: python -I tools/gen_dtors.py
"""
import contextlib
import importlib.util
import io
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("funcdiff", ROOT / "tools/funcdiff.py")
fd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fd)


def norm(body):
    ins = [re.sub(r"\s+", " ", l.split("*/", 1)[1].strip()) for l in body.splitlines() if "*/" in l]
    return " ; ".join(re.sub(r"\.L[0-9A-F]+", "L", i) for i in ins)


def main():
    text = (ROOT / "asm/us/text.s").read_text()
    blocks = dict(re.findall(r"^glabel func_([0-9A-F]+)\n(.*?)^endlabel", text, re.M | re.S))
    ref = norm(blocks["001AA7F0"])
    taken = set(re.findall(r"=\s*0x([0-9A-F]+);", (ROOT / "config/SLUS_209.64/symbols.txt").read_text()))
    addrs = sorted(a for a, b in blocks.items()
                   if int(a, 16) >= 0x195158 and norm(b) == ref and a.lstrip("0") not in taken)
    cls = {a: f"CUnk{a.lstrip('0')}" for a in addrs}
    out = ROOT / "src/game/auto/dtors.cpp"
    body = "".join(f"class {c} {{ public: ~{c}(); }};\n{c}::~{c}() {{}}\n" for c in cls.values())
    hdr = ("// AUTO-GENERATED by tools/gen_dtors.py: MW empty-body deleting destructors.\n"
           "// Verified byte-for-byte; class names are placeholders (CUnk<addr>).\n")
    out.write_text(hdr + body)
    obj = "scratch/gen/dtors.o"
    subprocess.run(["docker", "exec", "-w", "/w", "dmc3b", "sh", "-c",
                    "MWCIncludes=. wibo tools/compilers/mwcps2-3.0b52-030722/mwccps2.exe -c -O3,p -fl divbyzerocheck "
                    f"-lang c++ -Cpp_exceptions off -nostdinc -o {obj} src/game/auto/dtors.cpp"], check=True)
    ok = []
    for a, c in cls.items():
        mangled = f"__dt__{len(c)}{c}Fv"
        with contextlib.redirect_stdout(io.StringIO()):
            if fd.main(str(ROOT / "orig/SLUS_209.64/SLUS_209.64"), str(ROOT / obj), mangled, "0x" + a) == 0:
                ok.append((a, c, mangled))
    out.write_text(hdr + "".join(f"class {c} {{ public: ~{c}(); }};\n{c}::~{c}() {{}}\n" for _, c, _ in ok))
    (ROOT / "config/SLUS_209.64/symbols.auto.txt").write_text(
        "// AUTO-GENERATED by tools/gen_dtors.py\n" + "".join(f"{m} = 0x{a};\n" for a, _, m in ok))
    print(f"empty-body destructors: {len(ok)}/{len(cls)} match")


if __name__ == "__main__":
    main()
